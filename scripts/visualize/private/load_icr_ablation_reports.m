function [reports, runDir] = load_icr_ablation_reports(runDir)
%LOAD_ICR_ABLATION_REPORTS 表格与补充曲线共用同一正式 compensated 测试报告。
if nargin < 1 || isempty(runDir)
    projectDir = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
    runDir = fullfile(projectDir, 'outputs', 'runs', 'icr_ad_current_20261031_133445');
end
channels = {'NOF1', 'NCS1'};
groups = {'A', 'B', 'C', 'D'};
reports = cell(1, numel(channels));
for c = 1:numel(channels)
    path = fullfile(runDir, 'test', lower(channels{c}), 'comparison.json');
    assert(isfile(path), '找不到消融指标文件：%s', path);
    report = jsondecode(fileread(path));
    assert(isfield(report, 'complete') && report.complete && ...
        isfield(report, 'split') && strcmp(report.split, 'test') && ...
        isfield(report, 'input_view') && strcmp(report.input_view, 'compensated') && ...
        isfield(report, 'channel') && strcmp(report.channel, channels{c}), ...
        '需要 %s 已完成的 compensated CSI 测试报告：%s', channels{c}, path);
    assert(isequal(report.snr_db(:), (0:5:30)') && ...
        isfield(report, 'curves') && isequal(sort(fieldnames(report.curves)), groups'), ...
        '需要 0:5:30 dB 的完整正式 A-D 消融组：%s', path);
    for k = 1:numel(groups)
        row = report.curves.(groups{k});
        assert(all(isfield(row, {'ber', 'errors', 'total_bits', ...
            'mean_nmse_linear', 'mean_nmse_db'})), '消融指标字段不完整：%s / %s', path, groups{k});
        ber = row.ber(:);
        bits = row.total_bits(:);
        errors = row.errors(:);
        nmse = row.mean_nmse_linear(:);
        nmseDb = row.mean_nmse_db(:);
        assert(isequal(size(ber), [7, 1]) && isequal(size(bits), size(ber)) && ...
            isequal(size(errors), size(ber)) && all(isfinite(bits) & bits > 0 & bits == fix(bits)) && ...
            all(isfinite(errors) & errors >= 0 & errors <= bits & errors == fix(errors)) && ...
            all(isfinite(ber) & ber >= 0 & ber <= 1) && ...
            all(abs(ber - errors ./ bits) <= 1e-12 * max(ber, eps)), ...
            'BER 与误码计数不一致：%s / %s', path, groups{k});
        assert(isequal(size(nmse), size(ber)) && isequal(size(nmseDb), size(ber)) && ...
            all(isfinite(nmse) & nmse > 0) && all(isfinite(nmseDb)) && ...
            all(abs(nmseDb - 10 * log10(nmse)) < 1e-10), ...
            'NMSE 必须在线性域求均值后转 dB：%s / %s', path, groups{k});
    end
    assert(isequal(report.curves.A.mean_nmse_linear, report.curves.B.mean_nmse_linear), ...
        '固定 CSI 的 A/B 组 NMSE 必须一致：%s', path);
    reports{c} = report;
end
end

% Plot NOF1/NCS1 initial, DD-DPSS and CRU-Net CSI NMSE in one MATLAB figure.
% Run from any working directory. No figures or data are exported.
% Report values are already 10*log10(mean(linear NMSE)): use a linear dB axis.

scriptDirectory = fileparts(mfilename('fullpath'));
projectRoot = fileparts(fileparts(scriptDirectory));
comparisonConfig = jsondecode(fileread(fullfile(projectRoot, ...
    'configs', 'evaluation', 'ber_comparison.json')));
resultsRoot = fullfile(projectRoot, comparisonConfig.output);

channels = {'NOF1', 'NCS1'};
acceptedEndpoints = [-12.70 -18.30; -6.20 -10.67];
nmseData = cell(1, numel(channels));
for channelIndex = 1:numel(channels)
    reportPath = fullfile(resultsRoot, lower(channels{channelIndex}), 'metrics.json');
    nmseData{channelIndex} = load_nmse_report(reportPath, ...
        channels{channelIndex}, acceptedEndpoints(channelIndex, :));
end

% Match the BER figures' typography, frame, legend and visible grid lines.
style = struct();
style.colors = [0.12 0.47 0.71; 0.79 0.08 0.29];
style.initialMarkers = {'o', '^'};
style.ddMarkers = {'+', 'x'};
style.correctedMarkers = {'s', 'd'};
style.figureSize = [3.5 2.8]; % ICC single-column width, inches.
style.fontName = 'Arial';
style.fontSize = 9;

figureNmse = figure('Name', 'NOF1 / NCS1 NMSE-SNR', 'NumberTitle', 'off', ...
    'Color', 'w', 'WindowStyle', 'normal', 'Units', 'inches', ...
    'Position', [1.0 1.2 style.figureSize]);
ax = axes('Parent', figureNmse, 'Units', 'normalized', ...
    'Position', [0.16 0.15 0.81 0.81]);
hold(ax, 'on');
set(ax, 'XScale', 'linear', 'YScale', 'linear', 'FontName', style.fontName, ...
    'FontSize', style.fontSize, 'LineWidth', 0.7, 'Box', 'on', ...
    'TickDir', 'out', 'XMinorTick', 'off', 'YMinorTick', 'on', ...
    'XGrid', 'on', 'XMinorGrid', 'off', 'YGrid', 'on', 'YMinorGrid', 'on', ...
    'GridLineStyle', '-', 'MinorGridLineStyle', ':', ...
    'GridColor', [0.65 0.65 0.65], 'GridAlpha', 0.80, ...
    'MinorGridColor', [0.60 0.60 0.60], 'MinorGridAlpha', 0.60, ...
    'Layer', 'bottom');

curveHandles = gobjects(3, numel(channels)); % One column per channel.
allNmseDb = [];
for channelIndex = 1:numel(channels)
    data = nmseData{channelIndex};
    color = style.colors(channelIndex, :);
    curveHandles(1, channelIndex) = plot(ax, data.snrDb, data.initialDb, ...
        'Color', color, 'LineStyle', '--', 'LineWidth', 1.0, ...
        'Marker', style.initialMarkers{channelIndex}, 'MarkerSize', 4.5, ...
        'MarkerFaceColor', 'w', ...
        'DisplayName', [channels{channelIndex} ' - Estimate CSI']);
    curveHandles(2, channelIndex) = plot(ax, data.snrDb, data.ddDb, ...
        'Color', color, 'LineStyle', '-.', 'LineWidth', 1.0, ...
        'Marker', style.ddMarkers{channelIndex}, 'MarkerSize', 6, ...
        'DisplayName', [channels{channelIndex} ' - DD-DPSS']);
    % CRU-Net is the paper label for the icr_mmse corrected CSI in the report.
    curveHandles(3, channelIndex) = plot(ax, data.snrDb, data.correctedDb, ...
        'Color', color, 'LineStyle', '-', 'LineWidth', 1.0, ...
        'Marker', style.correctedMarkers{channelIndex}, 'MarkerSize', 4.5, ...
        'MarkerFaceColor', color, ...
        'DisplayName', [channels{channelIndex} ' - CRU-Net']);
    allNmseDb = [allNmseDb data.initialDb data.ddDb data.correctedDb]; %#ok<AGROW>
end

xlim(ax, [-1.5 31.5]);
xticks(ax, 0:5:30);
lowerLimit = 2 * floor((min(allNmseDb) - 0.8) / 2);
upperLimit = 2 * ceil((max(allNmseDb) + 4.5) / 2); % Leave room for three legend rows.
ylim(ax, [lowerLimit upperLimit]);
yticks(ax, lowerLimit:2:upperLimit);
minorTicks = lowerLimit:1:upperLimit;
ax.YAxis.MinorTickValues = setdiff(minorTicks, ax.YTick);
xlabel(ax, 'SNR (dB)', 'FontSize', style.fontSize + 1);
ylabel(ax, 'NMSE (dB)', 'FontSize', style.fontSize + 1);
legendHandle = legend(ax, curveHandles(:), 'Location', 'north', 'NumColumns', 2, ...
    'Interpreter', 'none', 'FontName', style.fontName, 'FontSize', 8, ...
    'Box', 'on', 'Color', 'w', 'EdgeColor', [0.3 0.3 0.3], 'LineWidth', 0.7);
legendHandle.ItemTokenSize = [10 6];
hold(ax, 'off');
configure_icc_metric_figure(figureNmse, ax);
drawnow;

function data = load_nmse_report(reportPath, channel, acceptedEndpoints)
    assert(isfile(reportPath), 'NMSEPlot:MissingReport', ...
        'Report not found: %s', reportPath);
    report = jsondecode(fileread(reportPath));
    assert(report.complete && ~report.smoke && strcmp(report.channel, channel) ...
        && strcmp(report.input_view, 'compensated') ...
        && strcmp(report.nmse.split, 'test'), 'NMSEPlot:InvalidReport', ...
        'Expected a complete compensated-CSI test report for %s.', channel);
    assert(isfield(report.nmse, 'corrected_mean_nmse_db'), ...
        'NMSEPlot:MissingCorrectedCSI', 'Corrected CSI NMSE is missing: %s', reportPath);
    data.snrDb = report.snr_db(:).';
    data.initialDb = report.nmse.mean_nmse_db(:).';
    [~, data.ddDb] = load_soft_dd_dpss(report, reportPath);
    data.correctedDb = report.nmse.corrected_mean_nmse_db(:).';
    assert(isequal(data.snrDb, 0:5:30), 'NMSEPlot:InvalidSnr', ...
        'Expected the SNR grid 0:5:30 dB for %s.', channel);
    assert(numel(data.initialDb) == numel(data.snrDb) ...
        && numel(data.ddDb) == numel(data.snrDb) && numel(data.correctedDb) == numel(data.snrDb) ...
        && all(isfinite([data.initialDb data.ddDb data.correctedDb])), ...
        'NMSEPlot:InvalidValues', 'NMSE values are incomplete or invalid: %s', reportPath);
    assert(all(abs(data.initialDb([1 end]) - acceptedEndpoints) < 0.02), ...
        'NMSEPlot:InvalidInputCSI', ...
        'Input CSI NMSE does not match the accepted %s endpoints.', channel);
end
